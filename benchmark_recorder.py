import json
from pathlib import Path
from typing import Optional, Dict, Any
import httpx
from bs4 import BeautifulSoup

from config import BASE_DIR, USER_AGENT
from auditor import WebsiteAuditor
from evidence import EvidenceGraph

BENCHMARK_DIR = BASE_DIR / "benchmark" / "dentists"

class BenchmarkRecorder:
    """Tooling to systematically scale the benchmark dataset from 5 to 100+ clinics."""

    @classmethod
    async def record_fixture(
        cls,
        url: str,
        clinic_name: str,
        fixture_slug: Optional[str] = None
    ) -> Path:
        slug = fixture_slug or "".join(c.lower() for c in clinic_name if c.isalnum() or c == "_")
        target_dir = BENCHMARK_DIR / f"clinic_{slug}"
        target_dir.mkdir(parents=True, exist_ok=True)

        if not url.startswith("http://") and not url.startswith("https://"):
            url = "https://" + url

        headers = {"User-Agent": USER_AGENT}
        async with httpx.AsyncClient(headers=headers, timeout=15.0, follow_redirects=True, verify=False) as client:
            resp = await client.get(url)
            html_content = resp.text

        # Save homepage.html
        html_file = target_dir / "homepage.html"
        with open(html_file, "w", encoding="utf-8") as f:
            f.write(html_content)

        # Generate initial draft expected.json using auditor
        auditor = WebsiteAuditor()
        soup = BeautifulSoup(html_content, "html.parser")
        graph = EvidenceGraph()
        tech_detail = auditor._match_declarative_fingerprints(html_content, soup, resp.headers, graph, url)
        has_booking, _, _ = auditor._check_booking_links(soup)

        expected_schema = {
            "clinic_name": clinic_name,
            "url": url,
            "expected": {
                "booking": len(tech_detail.booking_tools) > 0 or has_booking,
                "chatbot": len(tech_detail.chatbots) > 0,
                "cms": tech_detail.cms_and_frameworks[0] if tech_detail.cms_and_frameworks else None,
                "ga4": any("analytics 4" in a.lower() or "ga4" in a.lower() for a in tech_detail.analytics) or "G-" in html_content,
                "ad_pixels": len(tech_detail.ad_pixels) > 0 or "fbevents.js" in html_content,
                "ssl": url.startswith("https://")
            },
            "verified_by_human": False,
            "notes": "Draft generated by BenchmarkRecorder. Please review and set verified_by_human to true."
        }

        json_file = target_dir / "expected.json"
        with open(json_file, "w", encoding="utf-8") as f:
            json.dump(expected_schema, f, indent=2)

        return target_dir
